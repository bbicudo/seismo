export function it(locale) {
  return locale === "en" ? EN : PT;
}

// +12,3% / −4% (sinal sempre visível; menos tipográfico)
export function signed(n, locale, digits = 0, unit = "%") {
  if (n == null) return "–";
  const nf = new Intl.NumberFormat(locale === "en" ? "en-GB" : "pt-BR", { maximumFractionDigits: digits, minimumFractionDigits: 0 });
  const s = nf.format(Math.abs(n));
  return `${n > 0 ? "+" : n < 0 ? "−" : "±"}${s}${unit}`;
}

export function trendClass(n) {
  return n == null ? "" : n > 0 ? "up" : n < 0 ? "down" : "";
}
